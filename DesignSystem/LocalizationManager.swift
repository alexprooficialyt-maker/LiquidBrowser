// MARK: - Supported App Languages (15 Languages)

public enum AppLanguage: String, CaseIterable, Identifiable, Codable, Sendable {
    case spanish    = "es"
    case english    = "en"
    case french     = "fr"
    case german     = "de"
    case italian    = "it"
    case portuguese = "pt"
    case catalan    = "ca"
    case japanese   = "ja"
    case korean     = "ko"
    case chinese    = "zh"
    case arabic     = "ar"
    case russian    = "ru"
    case dutch      = "nl"
    case polish     = "pl"
    case turkish    = "tr"

    public var id: String { rawValue }

    public var displayName: String {
        switch self {
        case .spanish:    return "Español"
        case .english:    return "English"
        case .french:     return "Français"
        case .german:     return "Deutsch"
        case .italian:    return "Italiano"
        case .portuguese: return "Português"
        case .catalan:    return "Català"
        case .japanese:   return "日本語"
        case .korean:     return "한국어"
        case .chinese:    return "中文"
        case .arabic:     return "العربية"
        case .russian:    return "Русский"
        case .dutch:      return "Nederlands"
        case .polish:     return "Polski"
        case .turkish:    return "Türkçe"
        }
    }

    public var nativeRegion: String {
        switch self {
        case .spanish:    return "España / Latinoamérica"
        case .english:    return "United States / UK"
        case .french:     return "France / Canada"
        case .german:     return "Deutschland / Österreich"
        case .italian:    return "Italia / Svizzera"
        case .portuguese: return "Brasil / Portugal"
        case .catalan:    return "Catalunya / Andorra"
        case .japanese:   return "日本"
        case .korean:     return "대한민국"
        case .chinese:    return "中国 / 台灣"
        case .arabic:     return "العالم العربي"
        case .russian:    return "Россия / СНГ"
        case .dutch:      return "Nederland / België"
        case .polish:     return "Polska"
        case .turkish:    return "Türkiye"
        }
    }

    public var localizedName: String {
        nativeRegion
    }

    // flagEmoji is now empty — real flags come from VectorFlagSystem
    public var flagEmoji: String { "" }

    public var isRTL: Bool {
        self == .arabic
    }
}

